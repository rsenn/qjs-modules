#!/usr/bin/env qjsm
/* doc-api.js: keeps the export list of every module doc in step with the code.
 * depends on: fs, path, process. input: the dump of utilities/api-surface.sh.
 * rule: the last section, "## Export list", is the only part ever rewritten.
 *
 *   doc-api.js [-n] SURFACE_DIR [DOCS_ROOT]
 *
 * SURFACE_DIR is an api-surface.sh output directory (INDEX.txt, modules/).
 * DOCS_ROOT is the project root, default the current directory. A module
 * with no doc gets a stub holding the block, to be completed by hand.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import * as path from 'path';

const HEADING = '\n## Export list\n';
const SPECIAL = {
  node_os: 'js/node-os',
  loaders_packages: 'js/loaders/packages',
  loaders_commonjs: 'js/loaders/commonjs',
  'loaders_package-aliases': 'js/loaders/package-aliases',
  loaders_node: 'js/node',
  loaders_nodeNames: 'js/node',
};

/* doc path of a module, relative to doc/: native/<name>.md or js/<name>.md */
function docOf(root, name) {
  if(SPECIAL[name]) return SPECIAL[name] + '.md';

  const dashed = name.replace(/_/g, '-');
  const native = existsSync(path.join(root, `quickjs-${dashed}.c`)) || existsSync(path.join(root, `quickjs-${name}.c`)) || name == 'std' || name == 'os';

  for(const dir of native ? ['native', 'js'] : ['js', 'native'])
    for(const n of [name, dashed]) if(existsSync(path.join(root, 'doc', dir, n + '.md'))) return `${dir}/${n}.md`;

  return `${native ? 'native' : 'js'}/${dashed}.md`;
}

const code = s => '`' + s + '`';

/* one dump line -> { group, scope, member, kind, accessor, isCall, type, value } */
function parseLine(line) {
  const brackets = [];
  let m;
  let kind = 'function';

  /* [Symbol.for('x')] holds dots, parentheses and quotes: hide them while splitting */
  let body = line.replace(/\[[^\]]*\]/g, b => `\u0004${brackets.push(b) - 1}\u0005`);
  const unmask = x => x.replace(/\u0004(\d+)\u0005/g, (_, i) => brackets[i]);

  if((m = /^(function|class|value|object)\s+(.*)$/.exec(body))) {
    kind = m[1];
    body = m[2];
  }

  const [, head, rest = ''] = /^([^:(=\s]+)\s*(.*)$/.exec(body) ?? [, body, ''];
  const parts = head.split('.').map(unmask);
  const group = parts[0];
  const tail = parts.slice(1);
  const proto = tail[0]?.startsWith('prototype');
  const first = proto ? tail[0].slice('prototype'.length) : null;
  const member = (proto ? [...(first ? [first] : []), ...tail.slice(1)] : tail).join('.');
  const accessor = /^:\s*(get\/set|get|set)\b/.exec(rest)?.[1];
  const isCall = rest.startsWith('(');
  const value = /^:\s*(\w+)\s*=\s*(.*)$/.exec(unmask(rest));

  return { group, scope: proto ? 'proto' : tail.length ? 'static' : 'top', member, kind, accessor, isCall, type: value?.[1], value: value?.[2] };
}

/* only numbers and booleans are shown: a string or object value is run-specific and can hold
 * secrets (process.env), paths or build info */
const shown = e => (/^(number|boolean|bigint)$/.test(e.type ?? '') ? e.value : undefined);
const RUNTIME_GROUPS = new Set(['env', 'argv', 'argv0', 'execArgv', 'execPath']);

/* the markdown of one module's export list */
function render(name, lines) {
  const groups = new Map();

  for(const l of lines) {
    if(!l.trim()) continue;

    const e = parseLine(l.trim());

    if(RUNTIME_GROUPS.has(e.group)) continue;
    if(!groups.has(e.group)) groups.set(e.group, { kind: null, items: [] });
    groups.get(e.group).items.push(e);
  }

  const out = ['## Export list', '', `Generated by \`utilities/doc-api.js\` from the \`${name}\` dump of \`utilities/api-surface.sh\`: ${lines.filter(Boolean).length} members. Edit the text above this block, not the block.`, ''];
  const top = { functions: [], values: [] };
  const named = [];

  for(const [g, { items }] of groups) {
    const own = items.filter(i => i.scope == 'top');
    const nested = items.filter(i => i.scope != 'top');

    if(!nested.length) {
      const e = own[0] ?? items[0];

      if(e.isCall || e.kind == 'function') top.functions.push(code(g + '()'));
      else top.values.push(code(shown(e) !== undefined ? `${g} = ${shown(e)}` : g));
    } else named.push([g, own[0], items]);
  }

  if(top.functions.length) out.push('**Functions:** ' + top.functions.join(', '), '');
  if(top.values.length) out.push('**Values:** ' + top.values.join(', '), '');

  for(const [g, own, items] of named) {
    const staticM = items.filter(i => i.scope == 'static' && (i.isCall || i.kind == 'function') && !i.type);
    const staticV = items.filter(i => i.scope == 'static' && !staticM.includes(i));
    const protoM = items.filter(i => i.scope == 'proto' && i.isCall);
    const protoA = items.filter(i => i.scope == 'proto' && !i.isCall);
    const what = own?.kind == 'class' || items.some(i => i.scope == 'proto') ? 'class' : 'object';

    out.push(`### ${code(g)}`, '', `${what}${items.some(i => i.member == 'constructor') ? ', constructible' : ''}`, '');

    const list = (title, arr, f) => arr.length && out.push(`- **${title}:** ` + arr.map(f).join(', '));

    list('static methods', staticM.filter(i => i.member != 'constructor'), i => code(i.member + '()'));
    list('static values', staticV, i => code(shown(i) !== undefined ? `${i.member} = ${shown(i)}` : i.member + (i.accessor ? ` (${i.accessor})` : '')));
    list('methods', protoM.filter(i => i.member != 'constructor'), i => code(i.member + '()'));
    list('properties', protoA, i => code(i.member + (i.accessor ? ` (${i.accessor})` : shown(i) !== undefined ? ` = ${shown(i)}` : '')));
    out.push('');
  }

  return out.join('\n');
}

function main(args) {
  const dry = args[0] == '-n';
  const [surface, root = '.'] = dry ? args.slice(1) : args;

  if(!surface) {
    console.error('usage: doc-api.js [-n] SURFACE_DIR [DOCS_ROOT]');
    return 1;
  }

  let n = 0;

  for(const row of readFileSync(path.join(surface, 'INDEX.txt'), 'utf8').split('\n')) {
    const name = row.split('\t')[0];

    if(!name || name.includes('/') || /^(deps|inst|_)/.test(name)) continue;

    const lines = readFileSync(path.join(surface, 'modules', name + '.txt'), 'utf8').split('\n').filter(Boolean);

    if(!lines.length) continue;

    const rel = docOf(root, name);
    const file = path.join(root, 'doc', rel);
    const block = render(name, lines);
    let text = existsSync(file) ? readFileSync(file, 'utf8') : `# ${name}\n\n(TODO: description)\n\n`;
    const a = text.indexOf(HEADING);

    text = (a >= 0 ? text.slice(0, a) : text).replace(/\n*$/, '\n\n') + block + '\n';

    console.log(`${dry ? 'would write' : 'wrote'} doc/${rel} (${lines.length} members)`);
    n++;

    if(!dry) {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }

  console.log(`${n} docs`);
  return 0;
}

process.exit(main(process.argv.slice(2)));
