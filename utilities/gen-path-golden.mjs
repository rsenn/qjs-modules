#!/usr/bin/env node
/* gen-path-golden.mjs: prints node:path's answers for fixed valid inputs as JS source.
 * run with node; the output is the `golden` table of tests/unittests/test-path-node.js.
 *
 * ```sh
 * node utilities/gen-path-golden.mjs > /tmp/golden.js
 * ```
 *
 * rule: posix only, valid inputs only; resolve() gets an absolute first
 * argument so the result does not depend on the current directory.
 */
import path from 'node:path';

const P = ['', '.', '..', '/', '//', 'a', 'a/', 'a//b', '/a/b/c.txt', 'a/b/../c', './a/./b/', '../../x', '/a/../..', 'a.b.c', '.bashrc', 'a/.bashrc', 'a/b.', 'a/..', '/a/b/', 'C:\\x\\y', '\\\\srv\\share', 'x/y/z.tar.gz', '/a/b/c.d/', '///a///b///'];
const calls = [];

for(const fn of ['basename', 'dirname', 'extname', 'normalize', 'isAbsolute', 'parse'])
  for(const p of P) calls.push([fn, [p]]);

for(const [p, s] of [['/a/b.txt', '.txt'], ['/a/b.txt', 'b.txt'], ['/a/b.txt', 'xt'], ['/a/b.txt/', '.txt'], ['b', 'b'], ['', ''], ['a.js', '.js']])
  calls.push(['basename', [p, s]]);

for(const args of [[], ['a'], ['a', 'b'], ['a', '', 'b'], ['/a', 'b', '..', 'c'], ['a', '/b'], ['', ''], ['a/', '/b/'], ['..', 'x'], ['a', '..', '..', 'b'], ['/', 'a'], ['.', '.']])
  calls.push(['join', args]);

for(const [a, b] of [['/a/b', '/a/b/c'], ['/a/b/c', '/a/b'], ['/a', '/b'], ['/a/b', '/a/b'], ['/a/b', '/a/bc'], ['/', '/a'], ['/a', '/']])
  calls.push(['relative', [a, b]]);

for(const args of [['/a', 'b'], ['/a', '/b'], ['/a', '../b'], ['/a/b', '..', '..', '..'], ['/'], ['/a/', 'b/'], ['/a//b', './c']])
  calls.push(['resolve', args]);

for(const o of [{ dir: '/a', base: 'b.txt' }, { root: '/', base: 'x' }, { dir: '/a', name: 'b', ext: '.txt' }, { name: 'b', ext: 'txt' }, { dir: 'a/', base: 'b' }, {}, { root: '/', dir: '/', base: 'x' }, { base: 'x', name: 'y' }])
  calls.push(['format', [o]]);

const lines = calls.map(([fn, args]) => `  [${JSON.stringify(fn)}, ${JSON.stringify(args)}, ${JSON.stringify(path[fn](...args))}],`);

console.log(`/* generated by utilities/gen-path-golden.mjs from node ${process.version}: [function, arguments, result] */`);
console.log('const golden = [');
console.log(lines.join('\n'));
console.log('];');
