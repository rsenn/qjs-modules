/* doc/native/textcode.md: the generated export list names every export of the textcode module.
 * qjsm only: textcode is a native module. Regenerate the list with utilities/api-surface.sh and
 * utilities/doc-api.js (Tier 32.13) when this fails. */
import * as textcode from 'textcode';
import { readFileSync } from 'fs';
import { assert, eq, tests } from '../../lib/tinytest.js';

const doc = readFileSync(import.meta.dirname + '/../../doc/native/textcode.md', 'utf8');
const list = doc.slice(doc.indexOf('\n## Export list\n'));

/* the names in "**Functions:** `a()`, `b()`" */
const documentedFunctions = () => [...(/\*\*Functions:\*\* (.*)/.exec(list)?.[1] ?? '').matchAll(/`(\w+)\(\)`/g)].map(m => m[1]);
const documentedClasses = () => [...list.matchAll(/^### `(\w+)`$/gm)].map(m => m[1]);

const exported = (kind, test) => Object.keys(textcode).filter(k => kind == typeof textcode[k] && test(textcode[k])).sort();
const isClass = f => /^class\b/.test(Function.prototype.toString.call(f)) || f.prototype !== undefined && Object.getOwnPropertyNames(f.prototype).length > 1;

tests({
  'the export list has a block'() {
    assert(list.includes('Generated by `utilities/doc-api.js`'), 'no generated block');
  },

  'every exported function is in the list'() {
    const documented = documentedFunctions();
    const missing = exported('function', f => !isClass(f)).filter(n => !documented.includes(n));

    eq('', missing.join());
  },

  'every function of the list is exported'() {
    const stale = documentedFunctions().filter(n => typeof textcode[n] != 'function');

    eq('', stale.join());
  },

  'every exported class is in the list'() {
    const documented = documentedClasses();
    const missing = exported('function', isClass).filter(n => !documented.includes(n));

    eq('', missing.join());
  },

  'every class of the list is exported'() {
    const stale = documentedClasses().filter(n => typeof textcode[n] != 'function');

    eq('', stale.join());
  },

  'fitTable is documented'() {
    assert(documentedFunctions().includes('fitTable'), documentedFunctions().join());
  },

  'the member count of the list is the count of its names'() {
    const count = +/: (\d+) members\./.exec(list)[1];
    const names = documentedFunctions().length + documentedClasses().length;
    /* a class counts its constructor, then lists its methods and properties */
    const members = [...list.matchAll(/^- \*\*(?:methods|properties):\*\* (.*)$/gm)].reduce((n, m) => n + m[1].split(', ').length, 0);

    eq(count, names + members + documentedClasses().length);
  },
});
